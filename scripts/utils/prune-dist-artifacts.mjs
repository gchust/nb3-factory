// Removes files a deployment never reads: type declarations, third-party source maps, third-party documentation, and
// package `database` directories that a complete compiled mirror has already superseded.
//
// The deployment tree is installed by `pnpm install --prod`, which fetches whole published packages. A package ships
// what its author chose to publish, and for most of them that includes the `.d.ts` files a consumer compiles against,
// the source maps a consumer debugs with, and a README. None of it is reachable from a running server: Node loads the
// `.js`, and nothing in the tree opens a declaration or a map unless a debugger asks for one.
//
// What this does NOT do is decide reachability. Every rule here is a file-extension rule applied to files nothing
// executes, which is why it is safe in a way that pruning by import graph is not — a scan that resolves specifiers can
// miss one, and the miss surfaces as a runtime failure on a deployed server. The exclusions below are the cases where
// an extension alone is not enough, and each exists because something actually reads the file.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { formatMegabytes } from './server-deps.mjs';

const rootDir = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
  '..',
);
const distDir = path.join(rootDir, 'dist');

/**
 * Trees to prune.
 *
 * Both are pruned because they are the same files. `dist/package.json` refers to each workspace package by a `file:`
 * path, and pnpm satisfies a `file:` dependency with hard links, so `vendor/x/dist/index.js` and
 * `node_modules/x/dist/index.js` share one inode. Deleting through one path leaves the other link — and therefore the
 * file — in place, and `tar` writes a hard-linked file into the archive as a full second copy.
 *
 * `vendor` exists only when an application is built inside this repository, where its NocoBase packages are
 * `workspace:` ranges that a deployment cannot resolve. An application generated by `create-app` depends on published
 * versions instead, so nothing is vendored and the directory is never created — the walk below simply finds nothing.
 */
const PRUNED_TREES = ['node_modules', 'vendor'];

/** Packages this repository builds, whose files follow different rules below. */
const isOwnPackage = (relativePath) =>
  relativePath.split(path.sep).includes('@nocobase');

const isDeclaration = (fileName) =>
  fileName.endsWith('.d.ts') ||
  fileName.endsWith('.d.cts') ||
  fileName.endsWith('.d.mts');

/**
 * Documentation that is not a license.
 *
 * A license, notice, or copyright file carries an attribution obligation that redistributing the tree does not
 * discharge, and all of them together are a rounding error against what this removes.
 */
const LICENSE_FILE = /^(licen[cs]e|notice|copying|copyright|patents)/i;

const isDocumentation = (fileName) =>
  /\.(md|markdown)$/i.test(fileName) && !LICENSE_FILE.test(fileName);

/**
 * Paths kept whole, each because something reads a file the rules above would otherwise remove.
 *
 * `typescript/lib` holds `lib.*.d.ts`, which are inputs to the compiler rather than declarations describing it.
 * `@nocobase/app-plugin-workflow` runs `ts.createProgram` at run time to typecheck a workflow's source, and a program
 * without its standard library reports every global as undefined. TypeScript is an optional peer, so it is usually
 * absent from the tree entirely — but a deployment that installs it must get a working one.
 */
const PRESERVED_PATHS = [path.join('typescript', 'lib')];

const isPreserved = (relativePath) =>
  PRESERVED_PATHS.some(
    (preserved) =>
      relativePath === preserved ||
      relativePath.startsWith(`${preserved}${path.sep}`),
  );

/**
 * Whether a file in the deployment tree can be removed.
 *
 * Source maps and documentation are removed for third-party packages only. This repository's own packages keep both,
 * for reasons that do not apply to a dependency:
 *
 * - A map turns a production stack trace back into the TypeScript that produced it, which is the difference between a
 *   diagnosable report and a line number in compiled output. Nobody debugs into `openai` on a deployed server; we do
 *   debug into our own plugins, and the whole set costs about 4 MB.
 * - A markdown file may be product data rather than documentation. `@nocobase/ai-employee` loads employees, skills,
 *   and tools by scanning directories for `prompt.md`, `SKILLS.md`, and `description.md`; removing those breaks
 *   loading with an error naming a file that was present when the plugin was built. Nothing here can see that from the
 *   file alone, so the whole scope is exempt.
 *
 * Declarations are removed everywhere. They describe types for a compiler, and a deployment does not compile.
 */
const shouldRemove = (relativePath, fileName) => {
  if (isPreserved(relativePath)) return false;
  if (isDeclaration(fileName)) return true;
  if (isOwnPackage(relativePath)) return false;
  return fileName.endsWith('.map') || isDocumentation(fileName);
};

/** How a package's source file is named once it has been compiled. */
const compiledName = (fileName) => {
  if (fileName.endsWith('.mts')) return fileName.replace(/\.mts$/, '.mjs');
  if (fileName.endsWith('.cts')) return fileName.replace(/\.cts$/, '.cjs');
  if (fileName.endsWith('.ts')) return fileName.replace(/\.ts$/, '.js');
  if (fileName.endsWith('.tsx')) return fileName.replace(/\.tsx$/, '.js');
  return fileName;
};

/**
 * Whether a package's `database` directory is fully superseded by its compiled mirror.
 *
 * Empty would be a wrong answer here, so a source file without a compiled counterpart means the directory is not
 * superseded and is left untouched.
 */
const isCompletelyCompiled = (sourceDir, compiledDir) => {
  let entries;
  try {
    entries = fs.readdirSync(sourceDir, { withFileTypes: true });
  } catch {
    return false;
  }
  for (const entry of entries) {
    const source = path.join(sourceDir, entry.name);
    if (entry.isDirectory()) {
      if (!isCompletelyCompiled(source, path.join(compiledDir, entry.name)))
        return false;
      continue;
    }
    if (!entry.isFile()) return false;
    if (!fs.existsSync(path.join(compiledDir, compiledName(entry.name))))
      return false;
  }
  return true;
};

/**
 * Whether a plugin's `database` directory is shadowing its own compiled output.
 *
 * A plugin declares its migrations, seeds and collections as paths under `./database`, and the resolver tries
 * `<package>/database/...` first and only then `<package>/dist/database/...`. A package that publishes its TypeScript
 * sources alongside the compiled copy therefore wins with the sources. That works under the repository's `tsx`-driven
 * CLI and fails on a deployment, where plain `node` refuses to strip types for a file inside `node_modules`:
 *
 *   Stripping types is currently unsupported for files under node_modules,
 *   for ".../app-plugin-ai-employee/database/migrations/202608260002_create_ai_employee.ts"
 *
 * The whole directory has to go, not just the files in it. Emptying it instead would be worse than leaving it: the
 * resolver returns the first candidate that *exists*, so a `database/migrations` directory left behind with no files
 * in it reports zero migrations and the compiled ones are never reached — a deployment that boots with its tables
 * missing. Removing the directory is what makes the fallback happen for migrations, seeds and collections alike.
 *
 * The compiled mirror is checked first, so a package that ships sources and nothing else is left intact rather than
 * broken.
 */
const isSupersededDatabaseDirectory = (directoryPath) => {
  if (path.basename(directoryPath) !== 'database') return false;
  const compiled = path.join(path.dirname(directoryPath), 'dist', 'database');
  if (!fs.existsSync(compiled)) return false;
  return isCompletelyCompiled(directoryPath, compiled);
};

/** Removes a directory, counting what it held, since the walk above will not reach inside it. */
const removeTree = (directoryPath, removed) => {
  let entries;
  try {
    entries = fs.readdirSync(directoryPath, { withFileTypes: true });
  } catch {
    return;
  }
  for (const entry of entries) {
    const entryPath = path.join(directoryPath, entry.name);
    if (entry.isDirectory()) {
      removeTree(entryPath, removed);
      continue;
    }
    if (!entry.isFile()) continue;
    let size;
    try {
      size = fs.lstatSync(entryPath).size;
    } catch {
      continue;
    }
    fs.rmSync(entryPath, { force: true });
    removed.count += 1;
    removed.bytes += size;
  }
  fs.rmSync(directoryPath, { recursive: true, force: true });
};

const prune = (directory, treeRoot, removed) => {
  let entries;
  try {
    entries = fs.readdirSync(directory, { withFileTypes: true });
  } catch {
    return;
  }

  for (const entry of entries) {
    const entryPath = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      // Checked before descending: the directory itself is what has to go, so
      // walking into it first would be wasted work and a second pass.
      if (isSupersededDatabaseDirectory(entryPath)) {
        removeTree(entryPath, removed);
        continue;
      }
      prune(entryPath, treeRoot, removed);
      continue;
    }
    if (!entry.isFile()) continue;

    const relativePath = path.relative(treeRoot, entryPath);
    if (!shouldRemove(relativePath, entry.name)) continue;

    // Reads the size before unlinking. A hard-linked file reports its full size from either path, and this walk
    // reaches each inode once because the second link is removed along with the first.
    let size;
    try {
      size = fs.lstatSync(entryPath).size;
    } catch {
      continue;
    }
    fs.rmSync(entryPath, { force: true });

    removed.count += 1;
    removed.bytes += size;
  }
};

if (!fs.existsSync(distDir)) {
  throw new Error('Missing dist. Run pnpm build first.');
}

const removed = { bytes: 0, count: 0 };
for (const tree of PRUNED_TREES) {
  prune(path.join(distDir, tree), path.join(distDir, tree), removed);
}

// Stated rather than silent. A build that quietly deletes files reads as "this is what the build produced", and the
// one thing worse than shipping something unnecessary is not knowing what was dropped when a deployment misbehaves.
console.log(
  `Removed ${removed.count} declaration, source map, documentation, and superseded source files from the deployment tree (${formatMegabytes(removed.bytes)}).`,
);
